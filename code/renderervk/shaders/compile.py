"""Added in OpenMOHAA Plus: compile the Vulkan renderer's shaders to SPIR-V and write vk_shaders.h.

Run after editing a shader (needs glslangValidator, Debian package glslang-tools):
  python3 code/renderervk/shaders/compile.py
The generated header is committed, so building the game does not need a shader compiler.
"""
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SHADERS = [("ffp.vert", "vk_ffp_vert"), ("ffp.frag", "vk_ffp_frag")]


def main():
    out = ["// Generated by code/renderervk/shaders/compile.py from the shaders in that folder; do not edit.",
           "// SPDX-License-Identifier: AGPL-3.0-or-later",
           "#pragma once", ""]
    with tempfile.TemporaryDirectory() as tmp:
        for source, name in SHADERS:
            spv = os.path.join(tmp, name + ".spv")
            subprocess.run(["glslangValidator", "-V", "--quiet", os.path.join(HERE, source), "-o", spv], check=True)
            data = open(spv, "rb").read()
            words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
            out.append(f"static const unsigned int {name}[] = {{")
            for i in range(0, len(words), 8):
                out.append("    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) + ",")
            out.append("};")
            out.append("")
    with open(os.path.join(HERE, "..", "vk_shaders.h"), "w", newline="\n") as f:
        f.write("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
